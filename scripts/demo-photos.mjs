// draws "witness sketch" placeholder images for exhibits that don't have a real photo yet.
// usage: pnpm demo-photos [--force]
// without --force existing files are left alone. with --force only files that are still the
// untouched demo (sha256 matches the manifest) get redrawn, so a real photo never gets overwritten
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "@playwright/test";
import { caseFile } from "../content/case.ts";

const force = process.argv.includes("--force");
const manifestPath = "assets/manifest.json";
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const sha = (buf) => createHash("sha256").update(buf).digest("hex");

const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage();
await page.setContent(
  '<!doctype html><link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Caveat:wght@500&family=Special+Elite&display=block">',
);
await page.addScriptTag({ path: "scripts/demo-photos/sketch.js" });
await page.evaluate(() =>
  Promise.all([document.fonts.load("40px Caveat"), document.fonts.load("40px 'Special Elite'")]),
);
const available = await page.evaluate(() => window.demoSketches);

for (const ex of caseFile.exhibits) {
  const file = join("public", ex.photo);
  const id = `demo-${ex.slug}`;
  const entry = manifest.assets.find((a) => a.id === id);
  if (existsSync(file)) {
    const untouchedDemo = entry && sha(readFileSync(file)) === entry.sha256;
    if (!force || !untouchedDemo) {
      console.log(`skip  ${file}${untouchedDemo ? " (demo exists)" : " (real photo)"}`);
      continue;
    }
  }
  if (!available.includes(ex.slug)) {
    console.warn(`none  ${file}: no sketch drawn for "${ex.slug}" yet`);
    continue;
  }
  const dataUrl = await page.evaluate((e) => window.renderDemo(e), {
    id: ex.id,
    slug: ex.slug,
    title: ex.board ?? ex.title,
  });
  const buf = Buffer.from(dataUrl.split(",")[1], "base64");
  writeFileSync(file, buf);
  const record = {
    id,
    kind: "illustration",
    source: "Generated by scripts/demo-photos.mjs (demo, replace with a real photo)",
    url: null,
    file: file.replaceAll("\\", "/"),
    author: "Ayaan Bagawan (generated)",
    licence: "Own work",
    usedIn: [`content/case.ts exhibit ${ex.id}`],
    sha256: sha(buf),
  };
  if (entry) Object.assign(entry, record);
  else manifest.assets.push(record);
  console.log(`draw  ${file} (${(buf.length / 1024).toFixed(0)} KB)`);
}

writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
await browser.close();
